# Which package code does the browser app need?
#
# The app does not install the package: it sources a single file made of the
# package functions it can reach from a list of entry points (a call-graph
# closure). Two things follow:
#  * code the app never calls (the database layer, every function that makes a
#    network request) is not shipped to the browser at all, so the app cannot
#    reach the network through it;
#  * only the packages that code uses have to be built for WebAssembly.
#
# These are plain functions (nothing runs when this file is sourced) so tests
# and tools/build_app.R share them.

app_entry_points <- function() {
  c(
    "bundle_new", "bundle_read", "bundle_write", "bundle_merge", "bundle_add_raw",
    "bundle_payload_kind", "bundle_players", "bundle_to_tables", "bundle_derived",
    "bundle_schema_version", "print.rallyr_bundle",
    "plot_session_trend", "plot_rally_length", "plot_stroke_speed",
    "plot_net_clearance", "plot_gap_distribution",
    "sv_token", "sv_api_base"
  )
}

# Top-level assignments of every R file: name -> list(file, text, names used).
app_collect_definitions <- function(r_dir) {
  files <- sort(list.files(r_dir, pattern = "\\.[Rr]$", full.names = TRUE))
  defs <- list()
  for (f in files) {
    exprs <- parse(f, keep.source = TRUE)
    refs <- attr(exprs, "srcref")
    for (i in seq_along(exprs)) {
      e <- exprs[[i]]
      is_assign <- is.call(e) && length(e) == 3L && as.character(e[[1]])[1] %in% c("<-", "=") &&
        (is.name(e[[2]]) || is.character(e[[2]]))
      if (!is_assign) next
      name <- as.character(e[[2]])
      rhs <- e[[3]]
      uses <- all.names(rhs)
      # all.names() does not look inside the default values of arguments.
      if (is.call(rhs) && identical(rhs[[1]], as.name("function")) && !is.null(rhs[[2]])) {
        for (arg in names(rhs[[2]])) {
          if (!identical(rhs[[2]][[arg]], quote(expr = ))) uses <- c(uses, all.names(rhs[[2]][[arg]]))
        }
      }
      defs[[name]] <- list(
        file = basename(f), order = length(defs),
        text = paste(as.character(refs[[i]]), collapse = "\n"),
        uses = unique(uses)
      )
    }
  }
  defs
}

# The definitions reachable from `entry`, in their original order.
app_closure <- function(r_dir, entry = app_entry_points()) {
  defs <- app_collect_definitions(r_dir)
  missing <- setdiff(entry, names(defs))
  if (length(missing) > 0L) {
    stop("Entry point(s) not defined in ", r_dir, ": ", paste(missing, collapse = ", "), call. = FALSE)
  }
  keep <- character(0)
  todo <- entry
  while (length(todo) > 0L) {
    nm <- todo[1]
    todo <- todo[-1]
    if (nm %in% keep) next
    keep <- c(keep, nm)
    todo <- c(todo, setdiff(intersect(defs[[nm]]$uses, names(defs)), keep))
  }
  keep <- keep[order(vapply(keep, function(k) defs[[k]]$order, numeric(1)))]
  list(names = keep, defs = defs[keep])
}

# Write the closure as one source file; returns the names written.
app_write_sources <- function(r_dir, path, entry = app_entry_points()) {
  cl <- app_closure(r_dir, entry)
  header <- c(
    "# Generated by tools/build_app.R from the package's R/ directory. Do not edit.",
    "# Only the functions the browser app can reach are included.",
    ""
  )
  body <- unlist(lapply(cl$defs, function(d) c(d$text, "")), use.names = FALSE)
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  writeLines(c(header, body), path)
  invisible(cl$names)
}

# The packages the app's code names: `pkg::name` / `pkg:::name` in the closure
# and in the app file, and plain `library(pkg)` calls in the app file (a
# `library(x, character.only = TRUE)` call names no fixed package). Comments
# and strings are not read as code. Used by tools/build_app.R to decide which
# WebAssembly packages the export must contain.
app_package_refs <- function(r_dir, app_file, entry = app_entry_points()) {
  cl <- app_closure(r_dir, entry)
  texts <- c(vapply(cl$defs, function(d) d$text, character(1)), paste(readLines(app_file, warn = FALSE), collapse = "\n"))
  refs <- character(0)
  for (txt in texts) {
    exprs <- parse(text = txt, keep.source = TRUE)
    pd <- utils::getParseData(exprs)
    refs <- c(refs, pd$text[pd$token == "SYMBOL_PACKAGE"])
  }
  app_lines <- readLines(app_file, warn = FALSE)
  app_lines <- app_lines[!grepl("^\\s*#", app_lines)]
  libs <- regmatches(app_lines, regexec("^\\s*(?:library|require)\\(\\s*([A-Za-z][A-Za-z0-9.]*)\\s*\\)", app_lines, perl = TRUE))
  refs <- c(refs, vapply(libs[lengths(libs) > 0L], function(m) m[2], character(1)))
  sort(unique(refs))
}

# Packages the Shinylive runtime already holds, so they are not exported as
# extra WebAssembly packages: R's own, and those preinstalled in the runtime's
# base library (named in <dest>/shinylive/webr/library.js.metadata). NULL when
# that file cannot be read (the caller must then say it cannot tell).
app_runtime_packages <- function(dest) {
  meta <- file.path(dest, "shinylive", "webr", "library.js.metadata")
  if (!file.exists(meta)) return(NULL)
  d <- tryCatch(jsonlite::fromJSON(meta, simplifyVector = FALSE), error = function(e) NULL)
  if (is.null(d) || length(d$files) == 0L) return(NULL)
  files <- vapply(d$files, function(f) f$filename, character(1))
  pre <- unique(sub("^/([^/]+)/DESCRIPTION$", "\\1", grep("^/[^/]+/DESCRIPTION$", files, value = TRUE)))
  if (length(pre) == 0L) return(NULL)
  sort(unique(c(pre, rownames(utils::installed.packages(priority = "base")))))
}
